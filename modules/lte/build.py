#!/usr/bin/env python3
"""Build modules/lte/modem-firmware.rsc from modem-firmware.src (readable script body).
Run after every edit of the .src:   python3 modules/lte/build.py
"""
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here / "modem-firmware.src").read_text()
esc = src.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n")
C = "modem firmware (LTE)"
POL = "ftp,reboot,read,write,policy,test,sensitive"
rsc = f"""# =============================================================================
# routeros-gitops :: modules/lte/modem-firmware.rsc — OPTIONAL. GENERATED by modules/lte/build.py
# from modules/lte/modem-firmware.src — edit the .src, then rebuild. Docs: docs/09-modem-firmware.md
#
# Weekly LTE modem firmware check (and upgrade in mode=auto) for every enabled lte interface.
# Not the RouterBOARD firmware (engine/10-maintenance.rsc does that).
#
# SETTINGS (secrets.map, override per site)
#   PLACEHOLDER_MODEM_FW_MODE         notify | auto      notify = only report a newer version
#   PLACEHOLDER_MODEM_FW_START_DATE   first run date     its weekday is the weekly run day
#   PLACEHOLDER_MODEM_FW_START_TIME   run time           keep it after the nightly maintenance window
#   PLACEHOLDER_MODEM_FW_PING_TARGET  reachability check after the upgrade
#
# FLOW per modem: skip if uptime < 1h, deploy flag present, or interface not running
#   -> firmware-upgrade check (installed vs latest) -> current | available (notify) |
#   upgrade (auto): event first (LTE drops), wait up to 15 min for link + ping,
#   else disable/enable the interface, else ONE reboot. No reboot loop: the script
#   only runs from its weekly scheduler, never at startup.
# EVENTS (via script_LOG_EVENT): modem_fw_current, modem_fw_available, modem_fw_skip,
#   modem_fw_unsupported, modem_fw_upgrade_start, modem_fw_upgraded, modem_fw_failed,
#   modem_fw_recovery, modem_fw_recovery_reboot
# Requires script_LOG_EVENT (engine/00-observability.rsc or a site equivalent).
# Remove: /system scheduler remove [find comment="{C}"]; /system script remove [find comment="{C}"]
# =============================================================================
/system scheduler remove [find comment="{C}"]
/system script remove [find comment="{C}"]
/system script add name=script_MODEM_FW comment="{C}" owner=admin dont-require-permissions=yes policy={POL} source="{esc}"
/system scheduler add name=schedule_MODEM_FW comment="{C}" interval=7d start-date=PLACEHOLDER_MODEM_FW_START_DATE start-time=PLACEHOLDER_MODEM_FW_START_TIME on-event="/system script run script_MODEM_FW" policy={POL}
:log info "modules/lte/modem-firmware installed (weekly)"
"""
(here / "modem-firmware.rsc").write_text(rsc)
print("wrote", here / "modem-firmware.rsc")
